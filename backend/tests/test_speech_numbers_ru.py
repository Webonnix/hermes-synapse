import pytest

from backend.speech_numbers_ru import cardinal, decimal, normalize_ru_numbers, ordinal


@pytest.mark.parametrize(
    ("n", "words"),
    [
        (0, "ноль"),
        (21, "двадцать один"),
        (101, "сто один"),
        (1001, "тысяча один"),
        (2000, "две тысячи"),
        (12500, "двенадцать тысяч пятьсот"),
        (1_000_000, "один миллион"),
        (2_000_000_000, "два миллиарда"),
        (-5, "минус пять"),
    ],
)
def test_cardinal(n, words):
    assert cardinal(n) == words


@pytest.mark.parametrize(
    ("n", "form", "words"),
    [
        (1, "m", "первый"),
        (2, "m", "второй"),
        (3, "gen", "третьего"),
        (19, "n", "девятнадцатое"),
        (22, "f", "двадцать вторая"),
        (40, "m", "сороковой"),
        (100, "m", "сотый"),
        (2000, "m", "двухтысячный"),
        (2026, "gen", "две тысячи двадцать шестого"),
        (2026, "prep", "две тысячи двадцать шестом"),
    ],
)
def test_ordinal(n, form, words):
    assert ordinal(n, form) == words


def test_decimal():
    assert decimal(3, "5") == "три целых пять десятых"
    assert decimal(1, "25") == "одна целая двадцать пять сотых"


